/**
 * YouTube cookie input parser — powers the admin "Direct sign-in" system.
 *
 * The admin pastes whatever they captured from their signed-in YouTube session
 * and this module turns it into a valid Netscape cookies.txt for yt-dlp.
 * Auto-detects ALL the common capture formats:
 *
 *   1. Netscape cookies.txt (extension export, "# Netscape HTTP Cookie File")
 *   2. JSON array export    ([{"name":"SID","value":"…","domain":".youtube.com",…}])
 *   3. JSON object          ({"SID":"…","HSID":"…"} — DevTools copy of a header object)
 *   4. Cookie request header ("SID=…; HSID=…; SSID=…; …" — the whole `cookie:` line)
 *   5. Set-Cookie line(s)   ("SID=…; Domain=.youtube.com; Path=/; HttpOnly; …")
 *
 * Google/YouTube login lives in HttpOnly cookies (SID/HSID/SSID/SAPISID), so a
 * signed-in session ALWAYS contains them; if none are found the paste was made
 * without being signed in — the caller surfaces that as a guest-session warning.
 */

export type CookieRecord = {
  name: string;
  value: string;
  domain: string; // always normalized to a youtube.com domain (leading dot → subdomains)
  path: string;
  expires: number; // unix seconds
  secure: boolean;
  httpOnly: boolean;
};

export type ParsedCookies =
  | {
      ok: true;
      format: "netscape" | "json-array" | "json-object" | "header" | "set-cookie";
      cookies: CookieRecord[];
      netscape: string;
      authFound: string[]; // login-carrying cookies present in the paste
      guest: boolean; // true → no login cookies detected
      notes: string[]; // human-readable warnings (English keys, UI translates)
    }
  | { ok: false; error: string };

/** Cookies that actually carry Google/YouTube authentication. */
const AUTH_COOKIE_NAMES = new Set([
  "SID",
  "HSID",
  "SSID",
  "APISID",
  "SAPISID",
  "SIDCC",
  "LOGIN_INFO",
  "__Secure-1PSID",
  "__Secure-3PSID",
  "__Secure-1PSIDTS",
  "__Secure-3PSIDTS",
  "__Secure-1PSIDCC",
  "__Secure-3PSIDCC",
  "__Secure-ENID",
]);

const YT_DOMAIN_RE = /(^|\.)(youtube\.com|youtu\.be|youtube-nocookie\.com)$/i;
const YEAR_SECONDS = 365 * 24 * 3600;
const MAX_EXPIRES_SECONDS = 400 * 24 * 3600; // yt-dlp caps far-future expiries anyway

function normDomain(raw: string | undefined): string {
  let d = (raw ?? "").trim().toLowerCase().replace(/^\*/, "");
  if (!d) return ".youtube.com";
  if (!d.includes(".")) return ".youtube.com";
  if (d.startsWith(".")) return d;
  return YT_DOMAIN_RE.test(d) ? `.${d}` : `.${d}`; // leading dot → include subdomains
}

function normName(name: string): string {
  return name.trim().replace(/^"|"$/g, "");
}

function sanitizeValue(v: string): string {
  return v.trim().replace(/^"|"$/g, "").replace(/[\r\n\t]+/g, "%09");
}

function clampExpires(unixSeconds: number): number {
  const now = Math.floor(Date.now() / 1000);
  if (!Number.isFinite(unixSeconds) || unixSeconds <= now) return now + YEAR_SECONDS;
  return Math.min(unixSeconds, now + MAX_EXPIRES_SECONDS);
}

function toNetscapeLine(c: CookieRecord): string {
  const domain = c.domain.startsWith(".") ? c.domain : `.${c.domain}`;
  const flag = domain.startsWith(".") ? "TRUE" : "FALSE";
  const expiry = Math.floor(c.expires);
  return [
    domain,
    flag,
    c.path || "/",
    c.secure ? "TRUE" : "FALSE",
    String(expiry),
    c.httpOnly ? "#HttpOnly_" + c.name : c.name,
    c.value,
  ].join("\t");
}

function buildNetscape(cookies: CookieRecord[]): string {
  const lines = cookies.map(toNetscapeLine);
  return `# Netscape HTTP Cookie File\n# Generated by TuneLoad direct sign-in\n${lines.join("\n")}\n`;
}

type CookieFormat = "netscape" | "json-array" | "json-object" | "header" | "set-cookie";

function summarize(cookies: CookieRecord[], format: CookieFormat): ParsedCookies {
  const authFound = [...new Set(cookies.map((c) => c.name))].filter((n) => AUTH_COOKIE_NAMES.has(n));
  const notes: string[] = [];
  // Secure-flag repair: YouTube auth cookies are https-only; some JSON exports
  // omit the flag, and yt-dlp then refuses to send them.
  let repairedSecure = 0;
  for (const c of cookies) {
    if (!c.secure) {
      c.secure = true;
      repairedSecure++;
    }
    if (!c.path) c.path = "/";
    c.expires = clampExpires(c.expires);
  }
  if (repairedSecure) notes.push(`secure-flag-repaired:${repairedSecure}`);
  const kept = cookies.filter((c) => YT_DOMAIN_RE.test(c.domain.replace(/^\.+/, "")) || c.domain === ".youtube.com");
  const dropped = cookies.length - kept.length;
  if (dropped) notes.push(`non-youtube-dropped:${dropped}`);
  if (!authFound.length) notes.push("guest-session");
  return {
    ok: true,
    format,
    cookies: kept,
    netscape: buildNetscape(kept),
    authFound,
    guest: authFound.length === 0,
    notes,
  };
}

function parseJsonArray(arr: unknown[]): ParsedCookies | null {
  const out: CookieRecord[] = [];
  for (const item of arr) {
    if (typeof item !== "object" || item === null) continue;
    const j = item as Record<string, unknown>;
    const name = normName(String(j.name ?? j.Name ?? j.key ?? ""));
    const value = sanitizeValue(String(j.value ?? j.Value ?? ""));
    if (!name || !value) continue;
    out.push({
      name,
      value,
      domain: normDomain(typeof j.domain === "string" ? j.domain : undefined),
      path: typeof j.path === "string" && j.path ? j.path : "/",
      expires: clampExpires(Number(j.expirationDate ?? j.expires ?? j.expire ?? 0)),
      secure: j.secure === true || j.secure === "true" || YT_DOMAIN_RE.test(String(j.domain ?? "")),
      httpOnly: j.httpOnly === true || j.httpOnly === "true",
    });
  }
  if (!out.length) return null;
  return summarize(out, "json-array");
}

function parseJsonObject(obj: Record<string, unknown>): ParsedCookies | null {
  const out: CookieRecord[] = [];
  for (const [k, v] of Object.entries(obj)) {
    const value = sanitizeValue(String(v ?? ""));
    if (!value) continue;
    out.push({
      name: normName(k),
      value,
      domain: ".youtube.com",
      path: "/",
      expires: clampExpires(0),
      secure: true,
      httpOnly: AUTH_COOKIE_NAMES.has(k),
    });
  }
  if (!out.length) return null;
  return summarize(out, "json-object");
}

function parseHeaderString(raw: string): ParsedCookies | null {
  const body = raw.replace(/^cookie\s*:\s*/i, "").trim();
  if (!/=./.test(body)) return null;
  const out: CookieRecord[] = [];
  for (const pair of body.split(/\s*;\s*/)) {
    const eq = pair.indexOf("=");
    if (eq <= 0) continue;
    const name = normName(pair.slice(0, eq));
    const value = sanitizeValue(pair.slice(eq + 1));
    if (!name || !value) continue;
    out.push({
      name,
      value,
      domain: ".youtube.com",
      path: "/",
      expires: clampExpires(0),
      secure: true,
      httpOnly: AUTH_COOKIE_NAMES.has(name),
    });
  }
  if (out.length < 2) return null;
  return summarize(out, "header");
}

function parseSetCookieLines(lines: string[]): ParsedCookies | null {
  const out: CookieRecord[] = [];
  for (const line of lines) {
    const body = line.replace(/^set-cookie\s*:\s*/i, "").trim();
    const parts = body.split(/\s*;\s*/);
    const first = parts[0] ?? "";
    const eq = first.indexOf("=");
    if (eq <= 0) continue;
    const name = normName(first.slice(0, eq));
    const value = sanitizeValue(first.slice(eq + 1));
    if (!name || !value) continue;
    let domain = "";
    let path = "/";
    let expires = 0;
    let secure = false;
    let httpOnly = false;
    for (const attr of parts.slice(1)) {
      const [ak, ...rest] = attr.split("=");
      const key = ak.trim().toLowerCase();
      const val = rest.join("=").trim();
      if (key === "domain") domain = val;
      else if (key === "path") path = val || "/";
      else if (key === "expires") {
        const t = Date.parse(val);
        if (Number.isFinite(t)) expires = Math.floor(t / 1000);
      } else if (key === "secure") secure = true;
      else if (key === "httponly") httpOnly = true;
    }
    out.push({
      name,
      value,
      domain: normDomain(domain),
      path: path || "/",
      expires: clampExpires(expires),
      secure,
      httpOnly,
    });
  }
  if (!out.length) return null;
  return summarize(out, "set-cookie");
}

function parseNetscapeLines(lines: string[]): ParsedCookies | null {
  const out: CookieRecord[] = [];
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("# ")) continue; // keep #HttpOnly_ names below
    const isHttpOnly = trimmed.startsWith("#HttpOnly_");
    const body = isHttpOnly ? trimmed.slice("#HttpOnly_".length) : trimmed;
    const cols = body.split("\t");
    if (cols.length < 7) continue;
    const [domain, , path, secure, expires, name, ...valueParts] = cols;
    const cName = normName(name);
    const cValue = sanitizeValue(valueParts.join("\t"));
    if (!cName || !cValue) continue;
    out.push({
      name: cName,
      value: cValue,
      domain: normDomain(domain),
      path: path || "/",
      expires: clampExpires(Number(expires)),
      secure: secure === "TRUE" || YT_DOMAIN_RE.test(domain.replace(/^\./, "")),
      httpOnly: isHttpOnly,
    });
  }
  if (!out.length) return null;
  return summarize(out, "netscape");
}

export function parseCookieInput(raw: string): ParsedCookies {
  const input = (raw ?? "").trim();
  if (!input) return { ok: false, error: "empty" };

  // 1) Netscape cookies.txt — tab-separated 7-column lines (allow stray headers)
  const lines = input.split(/\r?\n/);
  const tabbed = lines.filter((l) => l.trim() && (l.trim().startsWith("#HttpOnly_") || (!l.trim().startsWith("#") && l.split("\t").length >= 7)));
  if (tabbed.length >= 2) return parseNetscapeLines(tabbed);

  // 2) JSON — array export or {"cookies":[…]} wrapper or plain {name:value}
  if (input.startsWith("{") || input.startsWith("[")) {
    try {
      const parsed = JSON.parse(input) as unknown;
      if (Array.isArray(parsed)) {
        const r = parseJsonArray(parsed);
        if (r) return r;
      } else if (parsed && typeof parsed === "object") {
        const obj = parsed as Record<string, unknown>;
        if (Array.isArray(obj.cookies)) {
          const r = parseJsonArray(obj.cookies as unknown[]);
          if (r) return r;
        }
        const r = parseJsonObject(obj);
        if (r) return r;
      }
    } catch {
      return { ok: false, error: "bad-json" };
    }
  }

  // 3) Set-Cookie line(s) — attribute soup is the tell
  const setCookieLines = lines.filter((l) => /;\s*(domain|path|expires|httponly|secure)\s*=/i.test(l) || /^set-cookie\s*:/i.test(l));
  if (setCookieLines.length) {
    const r = parseSetCookieLines(setCookieLines);
    if (r) return r;
  }

  // 4) Cookie request header — "k=v; k=v; …" (the most common paste)
  const r = parseHeaderString(input);
  if (r) return r;

  return { ok: false, error: "unrecognized" };
}
